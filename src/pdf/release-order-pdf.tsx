import { Document, Page, StyleSheet, Text, View } from "@react-pdf/renderer";
import type { ReleaseOrderPdfData } from "./release-order-data";

const green = "#3fa34d";
const s = StyleSheet.create({
  page: { padding: 36, fontSize: 10, fontFamily: "Helvetica", color: "#1a1a1a" },
  header: { flexDirection: "row", justifyContent: "space-between", borderBottomWidth: 1, borderColor: "#1a1a1a", paddingBottom: 10 },
  company: { fontSize: 15, fontFamily: "Helvetica-Bold" },
  bold: { fontFamily: "Helvetica-Bold" },
  muted: { color: "#6b6b6b" },
  banner: { marginTop: 18, borderWidth: 2, borderColor: green, backgroundColor: "#eef6ec", borderRadius: 8, padding: 16, alignItems: "center" },
  big: { fontSize: 26, fontFamily: "Helvetica-Bold", letterSpacing: 2, marginTop: 4 },
  grid: { flexDirection: "row", flexWrap: "wrap", marginTop: 16 },
  fact: { width: "33%", marginBottom: 10 },
  th: { fontFamily: "Helvetica-Bold", fontSize: 9 },
  row: { flexDirection: "row", borderBottomWidth: 1, borderColor: "#d9d9d9", paddingVertical: 5 },
});

const eat = (d: Date) => d.toLocaleString("en-GB", { timeZone: "Africa/Dar_es_Salaam", day: "numeric", month: "long", year: "numeric", hour: "2-digit", minute: "2-digit" });
const widths = ["6%", "24%", "40%", "12%", "18%"];

export function ReleaseOrderPdf({ data }: { data: ReleaseOrderPdfData }) {
  const { ro, invoice, customer, company, items } = data;
  const facts = [
    ["Customer", customer.name],
    ["Phone", customer.phone],
    ["Invoice", invoice.invoiceNo],
    ["Amount paid", `TZS ${Number(invoice.amountPaid).toLocaleString("en-US")}`],
    ["Issued", eat(ro.issuedAt)],
    ["Status", ro.collectedAt ? `Collected ${eat(ro.collectedAt)}` : "Ready for collection"],
  ];
  return (
    <Document title={`${ro.releaseNo} · ${company.name}`} author={company.name}>
      <Page size="A4" style={s.page}>
        <View style={s.header}>
          <Text style={s.company}>{company.name.toUpperCase()}</Text>
          <View style={{ alignItems: "flex-end" }}>
            {company.address?.split(",").map((part) => <Text key={part}>{part.trim()}</Text>)}
            {company.phone && <Text>Call: {company.phone}</Text>}
          </View>
        </View>

        <View style={s.banner}>
          <Text style={s.bold}>RELEASE ORDER / HATI YA KUCHUKUA MZIGO</Text>
          <Text style={s.big}>{ro.releaseNo}</Text>
          <Text style={[s.muted, { marginTop: 6 }]}>Fully paid. Show this at the warehouse to collect the goods below. / Imelipwa kikamilifu.</Text>
        </View>

        <View style={s.grid}>
          {facts.map(([k, v]) => (
            <View key={k} style={s.fact}>
              <Text style={s.muted}>{k}</Text>
              <Text style={s.bold}>{v}</Text>
            </View>
          ))}
        </View>

        <View style={[s.row, { borderColor: "#1a1a1a" }]}>
          {["SN", "Tracking No", "Description", "Packages", "Volume"].map((h, i) => (
            <Text key={h} style={[s.th, { width: widths[i] }]}>
              {h}
            </Text>
          ))}
        </View>
        {items.map((r, i) => (
          <View key={r.trackingNo} style={s.row} wrap={false}>
            {[String(i + 1), r.trackingNo, r.description ?? "-", String(r.packages), `${Number(r.volume)} ${r.volumeUnit}`].map((v, j) => (
              <Text key={j} style={{ width: widths[j] }}>
                {v}
              </Text>
            ))}
          </View>
        ))}

        <Text style={[s.muted, { marginTop: 24 }]}>
          Warehouse staff: confirm this release order in Zigopay before handing over the goods. Each release order can be used once.
        </Text>
        <Text style={[s.muted, { position: "absolute", bottom: 24, left: 36, fontSize: 7 }]} fixed>
          Generated by Zigopay
        </Text>
      </Page>
    </Document>
  );
}
